const fs = require('node:fs');
const path = require('node:path');
(async () => {
const { lexer } = await import('file:///C:/Users/dmitr/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/marked/lib/marked.esm.js');

const root = path.resolve(__dirname, '..');
const input = process.argv[2];
if (!input) throw new Error('Pass the supplied ERP Markdown file or attachment directory.');
const source = fs.statSync(input).isDirectory()
  ? path.join(input, fs.readdirSync(input).find(name => name.endsWith('.txt')))
  : input;
const markdown = fs.readFileSync(source, 'utf8');
const blocks = lexer(markdown).filter(token => token.type === 'code' && token.lang === 'html');
const ids = ['F1', 'F2', 'F3', 'F4', 'F6', 'F7', 'F8'];
if (blocks.length !== ids.length) throw new Error('Expected exactly seven ERP embeds.');
const entries = blocks.map(({ text }, index) => {
  const html = text.slice(0, text.indexOf('<style>')).trim();
  const script = text.match(/<script>\s*\(\(\) => \{([\s\S]*?)\}\)\(\);\s*<\/script>/)?.[1];
  if (!script || !html.includes('<form novalidate>')) throw new Error('Unknown embed structure.');
  const slug = html.match(/id="ni-crm-([^"]+)"/)?.[1];
  if (!slug || !script.includes(`/forms/${slug}/submissions`)) throw new Error('Mismatched endpoint.');
  // Keep the supplied protocol; adapt only DOM binding and documented client safeguards.
  let body = script.replace(/  const root = document\.getElementById\("[^"]+"\);\s*/, '');
  body = body.replace("    if (!form.reportValidity()) return;", "    if (form.querySelector('button[type=\"submit\"]').disabled || !form.reportValidity()) return;");
  body = body.replace("if (!response.ok) throw new Error('submit failed');", "if (!response.ok) throw new Error(response.status === 403 ? 'origin denied' : 'submit failed');");
  body = body.replace('    } catch {\n      result.textContent', '    } catch (error) {\n      result.textContent');
  body = body.replace("'Не удалось отправить заявку. Позвоните нам или повторите попытку позже.'", "error.message === 'origin denied' ? 'Отправка с этого адреса сайта пока не разрешена. Напишите нам на info@neuroiconica.ru.' : 'Не удалось отправить заявку. Данные сохранены в форме. Повторите попытку или напишите нам на info@neuroiconica.ru.'");
  body = body.replace('      form.reset();', '      if (telemetryTimer) window.clearTimeout(telemetryTimer);\n      telemetryTimer = null;\n      form.reset();');
  return `${JSON.stringify(ids[index])}: {html: ${JSON.stringify(html)}, init(root) {${body}\n}}`;
});
fs.writeFileSync(path.join(root, 'docs/erp-embed-codes-2026-10.md'), markdown);
fs.writeFileSync(path.join(root, 'js/erp-embeds.js'),
  '// Generated by tools/import-erp-embeds.cjs from the archived ERP export.\n' +
  'window.NeiroiconicaERPEmbeds = {\n' + entries.join(',\n') + '\n};\n');

const pages = ['index.html', ...['about', 'assistiv', 'neurobureau', 'products'].flatMap(dir =>
  fs.readdirSync(path.join(root, dir)).filter(name => name.endsWith('.html')).map(name => `${dir}/${name}`))];
let count = 0;
for (const file of pages) {
  const filename = path.join(root, file);
  let html = fs.readFileSync(filename, 'utf8');
  if (!html.includes('class="erp-form"')) continue;
  if (!html.includes('js/erp-embeds.js')) {
    html = html.replace(/<script src="([^"\n]*?)revision\.js"><\/script>/,
      '<script src="$1erp-embeds.js"></script>\n<script src="$1erp-forms.js"></script>\n$&');
    if (!html.includes('js/erp-embeds.js')) throw new Error(`Missing script anchor: ${file}`);
  }
  html = html.replace(/<!-- ВСТАВИТЬ КОД ФОРМЫ F\d ИЗ ERP -->/g, '<!-- ERP form mounts here; keep the email fallback for unavailable JavaScript. -->')
    .replaceAll('Форма появится здесь. Пока напишите нам на почту.', 'Напишите нам на почту:');
  fs.writeFileSync(filename, html);
  count++;
}
console.log(`Imported seven embeds; connected ${count} pages.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
